import React from 'react';
import { SectionCard } from '../ui/SectionCard';
import { Users, Info, ShieldAlert } from 'lucide-react';

export function PeerCluster({ cluster }) {
  if (!cluster) return null;

  const isInsufficient = cluster.has_peer_data === false || cluster.status === "insufficient_data";

  if (isInsufficient) {
    return (
      <SectionCard
        title="Machine-Learned Peer Cluster Comparison"
        subtitle="K-Means clustering algorithm evaluated across regional industrial peer database"
        badge={
          <span className="text-[10px] font-mono px-2 py-0.5 rounded bg-amber-950 text-amber-300 border border-amber-800">
            Defensibility Guard Active
          </span>
        }
      >
        <div className="p-4 rounded bg-[#151924] border border-[#232b3b] mb-4">
          <div className="flex items-center gap-2 mb-2 text-amber-400">
            <ShieldAlert className="w-4 h-4 shrink-0" />
            <h4 className="text-xs font-semibold">Insufficient Benchmark Peer Cohort</h4>
          </div>
          <p className="text-xs text-slate-300 leading-relaxed mb-3">
            {cluster.message || (
              `Statistically defensible K-Means clustering requires at least ${cluster.required_peer_count || 10} active industrial peer facilities in this sector with >=100 observations each. Currently, ${cluster.peer_count || 0} eligible peer facility is registered.`
            )}
          </p>

          <div className="grid grid-cols-1 sm:grid-cols-3 gap-2 text-xs font-mono pt-2 border-t border-[#232b3b]">
            <div className="p-2.5 rounded bg-[#10131b] border border-[#1b212f]">
              <span className="text-[10px] text-slate-400 uppercase block">Registered Peers</span>
              <span className="text-sm font-bold text-slate-200">{cluster.peer_count || 0} / {cluster.required_peer_count || 10}</span>
            </div>
            <div className="p-2.5 rounded bg-[#10131b] border border-[#1b212f]">
              <span className="text-[10px] text-slate-400 uppercase block">Observation Depth</span>
              <span className="text-sm font-bold text-amber-400">
                {cluster.criteria_status?.observation_depth_met ? 'Met' : 'Pending >=100'}
              </span>
            </div>
            <div className="p-2.5 rounded bg-[#10131b] border border-[#1b212f]">
              <span className="text-[10px] text-slate-400 uppercase block">Methodology Policy</span>
              <span className="text-sm font-bold text-slate-300">Zero Synthetic Bias</span>
            </div>
          </div>
        </div>

        <p className="text-[11px] text-slate-400 italic">
          Note: CircuLeak adheres to GHG Protocol audit standards. Synthetic peer fabrication is strictly prohibited.
        </p>
      </SectionCard>
    );
  }

  return (
    <SectionCard
      title="Machine-Learned Peer Cluster Comparison"
      subtitle="K-Means clustering generated by backend ML service based on plant output and process telemetry"
      badge={
        <span className="text-[10px] font-mono px-2 py-0.5 rounded bg-blue-950 text-blue-300 border border-blue-800">
          Cohort Clustered
        </span>
      }
    >
      <div className="p-3.5 rounded bg-[#151924] border border-[#232b3b] mb-4">
        <div className="flex items-center gap-2 mb-1">
          <Users className="w-4 h-4 text-blue-400" />
          <h4 className="text-xs font-semibold text-white">{cluster.cluster_name}</h4>
        </div>
        <p className="text-xs text-slate-300 leading-relaxed">
          {cluster.peer_characteristics?.validation || "Defensible cluster match based on regional operational peers."}
        </p>
      </div>

      <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 text-xs font-mono">
        <div className="p-3 rounded bg-[#131720] border border-[#212735]">
          <span className="text-[10px] text-slate-400 uppercase block">Cluster Size</span>
          <span className="text-lg font-bold text-slate-200">
            {cluster.peer_cohort_size || cluster.similar_facility_count || 0} Plants
          </span>
        </div>

        <div className="p-3 rounded bg-[#131720] border border-[#212735]">
          <span className="text-[10px] text-slate-400 uppercase block">Cluster Average</span>
          <span className="text-lg font-bold text-slate-200">
            {cluster.cohort_average_intensity || cluster.cluster_average || 0} kg/t
          </span>
        </div>

        <div className="p-3 rounded bg-[#131720] border border-[#212735]">
          <span className="text-[10px] text-slate-400 uppercase block">This Facility</span>
          <span className="text-lg font-bold text-blue-400">
            {cluster.facility_intensity || 0} kg/t
          </span>
        </div>

        <div className="p-3 rounded bg-[#131720] border border-[#212735]">
          <span className="text-[10px] text-slate-400 uppercase block">Cluster Gap</span>
          <span className={`text-lg font-bold ${(cluster.gap_to_cohort_avg_percent || cluster.gap_percent || 0) > 0 ? 'text-amber-400' : 'text-emerald-400'}`}>
            {(cluster.gap_to_cohort_avg_percent || cluster.gap_percent || 0) > 0 ? `+${cluster.gap_to_cohort_avg_percent || cluster.gap_percent}%` : `${cluster.gap_to_cohort_avg_percent || cluster.gap_percent}%`}
          </span>
        </div>
      </div>
    </SectionCard>
  );
}
